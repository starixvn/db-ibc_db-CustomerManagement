ALTER FUNCTION [dbo].f_GetVRBigStakeConfig(@Site NVARCHAR(50))	       
RETURNS TABLE
AS
/*
	Created by: 20210219@Eden
	Task: Return VRBigStakeConfig 
	DB: DBCust/CustDB,DBWH-bodb02
	Original: 
	
	Revisions:
		- 20210219@Eden: Initial version [Redmine: #150298]
		- 20221226@Tacy: NAP CM - Split 789y Site [RedmineID: #184879]

	Explanation's Param:

	Examples:
		SELECT * FROM dbo.f_GetVRBigStakeConfig('789y')
		SELECT * FROM dbo.f_GetVRBigStakeConfig(NULL)
		
*/ 
RETURN
	WITH Temp AS (
		SELECT '222223' AS Site, 1 AS Type, CONVERT(MONEY, 300000) AS Credit,  CONVERT(MONEY, 10000) AS StakeRM, CONVERT(SMALLMONEY, 1) AS VRValue, CONVERT(DATETIME,'2021/02/25') ReleasedDate UNION ALL
		SELECT '222225' AS Site, 1 AS Type, CONVERT(MONEY, 300000) AS Credit,  CONVERT(MONEY, 10000) AS StakeRM, CONVERT(SMALLMONEY, 1) AS VRValue, CONVERT(DATETIME,'2021/02/25') ReleasedDate UNION ALL
		SELECT '222227' AS Site, 1 AS Type, CONVERT(MONEY, 300000) AS Credit,  CONVERT(MONEY, 10000) AS StakeRM, CONVERT(SMALLMONEY, 1) AS VRValue, CONVERT(DATETIME,'2021/02/25') ReleasedDate UNION ALL
		SELECT '722222' AS Site, 1 AS Type, CONVERT(MONEY, 300000) AS Credit,  CONVERT(MONEY, 10000) AS StakeRM, CONVERT(SMALLMONEY, 1) AS VRValue, CONVERT(DATETIME,'2021/02/25') ReleasedDate UNION ALL
		SELECT '733333' AS Site, 1 AS Type, CONVERT(MONEY, 300000) AS Credit,  CONVERT(MONEY, 10000) AS StakeRM, CONVERT(SMALLMONEY, 1) AS VRValue, CONVERT(DATETIME,'2021/02/25') ReleasedDate UNION ALL
		SELECT Site, 1 AS Type, CONVERT(MONEY, 200000) AS Credit,  CONVERT(MONEY, 10000) AS StakeRM, CONVERT(SMALLMONEY, 1) AS VRValue, CONVERT(DATETIME,'2021/02/25') ReleasedDate FROM Site WITH (NOLOCK) WHERE SiteLabel='789y' UNION ALL
		SELECT '755555' AS Site, 1 AS Type, CONVERT(MONEY, 200000) AS Credit,  CONVERT(MONEY, 10000) AS StakeRM, CONVERT(SMALLMONEY, 1) AS VRValue, CONVERT(DATETIME,'2021/02/25') ReleasedDate UNION ALL
		SELECT 'INDO' AS Site, 1 AS Type, CONVERT(MONEY, 200000) AS Credit,  CONVERT(MONEY, 10000) AS StakeRM, CONVERT(SMALLMONEY, 1) AS VRValue, CONVERT(DATETIME,'2021/02/25') ReleasedDate UNION ALL
		SELECT 'IBCINDO' AS Site, 1 AS Type, CONVERT(MONEY, 200000) AS Credit,  CONVERT(MONEY, 10000) AS StakeRM, CONVERT(SMALLMONEY, 1) AS VRValue, CONVERT(DATETIME,'2021/02/25') ReleasedDate
	)
	SELECT * FROM Temp WHERE (Site = @Site OR @Site IS NULL)
GO